#!/usr/bin/env python3
"""Role lesson loop: run -> retro -> candidate -> human promotion -> role lesson.

Candidates are proposals from Main. Only a user-approved promotion writes to
the role lesson file that peers read at task start
(`~/.pi/agent/role-lessons/<role>.md`). Peers never edit these files.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import sys
from pathlib import Path

ROLES = {"worker", "reviewer", "security", "redteam", "oracle", "research", "browser"}
ROOT = Path(os.environ.get("ROLE_LESSONS_ROOT", Path.home() / ".pi/agent/role-lessons"))
MAX_LESSON = 400


def candidates_path() -> Path:
    return ROOT / "candidates.jsonl"


def rows() -> list[dict]:
    path = candidates_path()
    if not path.is_file():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line]


def append(entry: dict) -> None:
    ROOT.mkdir(parents=True, exist_ok=True)
    with candidates_path().open("a") as fh:
        fh.write(json.dumps(entry, ensure_ascii=False) + "\n")


def state() -> dict[str, dict]:
    """Fold the append-only log into the latest state per candidate."""
    out: dict[str, dict] = {}
    for r in rows():
        if r["event"] == "propose":
            out[r["id"]] = {**r, "status": "pending"}
        elif r["id"] in out:
            out[r["id"]]["status"] = r["event"]
    return out


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")


def propose(args: argparse.Namespace) -> int:
    lesson = " ".join(args.lesson.split())
    if args.role not in ROLES:
        raise SystemExit(f"unknown role: {args.role}")
    if not lesson or len(lesson) > MAX_LESSON:
        raise SystemExit(f"lesson must be 1..{MAX_LESSON} characters")
    if not args.evidence:
        raise SystemExit("a lesson needs at least one --evidence locator")
    cid = hashlib.sha256(f"{args.role}\0{lesson}".encode()).hexdigest()[:10]
    if cid in state():
        raise SystemExit(f"duplicate candidate: {cid}")
    append(
        {
            "event": "propose",
            "id": cid,
            "role": args.role,
            "lesson": lesson,
            "evidence": args.evidence,
            "created_at": now(),
        }
    )
    print(cid)
    return 0


def list_cmd(args: argparse.Namespace) -> int:
    items = [c for c in state().values() if args.all or c["status"] == "pending"]
    print(json.dumps(items, ensure_ascii=False, indent=2))
    return 0


def decide(args: argparse.Namespace, event: str) -> int:
    current = state()
    cand = current.get(args.id)
    if not cand:
        raise SystemExit(f"unknown candidate: {args.id}")
    if cand["status"] != "pending":
        raise SystemExit(f"candidate is already {cand['status']}")
    if event == "promoted":
        if not args.approved_by_user:
            raise SystemExit("promotion needs --approved-by-user (a human decision)")
        lesson_file = ROOT / f"{cand['role']}.md"
        if not lesson_file.exists():
            lesson_file.write_text(
                f"# {cand['role']} lessons\n\n"
                "Promoted by the user from evidence-backed retros. "
                "Apply each lesson; do not edit this file.\n\n"
            )
        with lesson_file.open("a") as fh:
            refs = ", ".join(cand["evidence"])
            fh.write(f"- {cand['lesson']} (id {cand['id']}; evidence: {refs})\n")
    append({"event": event, "id": args.id, "created_at": now()})
    print(json.dumps({"id": args.id, "status": event}))
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="command", required=True)
    pr = sub.add_parser("propose")
    pr.add_argument("--role", required=True)
    pr.add_argument("--lesson", required=True)
    pr.add_argument("--evidence", action="append", default=[])
    pr.set_defaults(func=propose)
    ls = sub.add_parser("list")
    ls.add_argument("--all", action="store_true")
    ls.set_defaults(func=list_cmd)
    pm = sub.add_parser("promote")
    pm.add_argument("id")
    pm.add_argument("--approved-by-user", action="store_true")
    pm.set_defaults(func=lambda a: decide(a, "promoted"))
    rj = sub.add_parser("reject")
    rj.add_argument("id")
    rj.set_defaults(func=lambda a: decide(a, "rejected"))
    args = p.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
